import { readFileSync, writeFileSync } from "node:fs";
import Ajv from "ajv/dist/2020.js";
import { _ } from "ajv";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone/index.js";
import { build } from "esbuild";
import { fileURLToPath } from "node:url";

const contracts = new URL("../../../contracts/", import.meta.url);
for (const [file, model] of [["task-view", "TaskView"], ["catalog-view", "CatalogView"], ["plan-view", "PlanView"], ["plan-list-view", "PlanListView"], ["control-view", "ControlView"], ["task-history-view", "TaskHistoryView"], ["comparison-report-view", "ComparisonReportViewV4"], ["preference-proposal-view", "PreferenceProposalViewV4"]]) {
const schema = JSON.parse(readFileSync(new URL(`${file}.schema.json`, contracts), "utf8"));
const ajv = new Ajv({ strict: false, code: {source: true, esm: true, formats: _`formats`} });
addFormats(ajv);
const validate = ajv.compile(schema);
await build({
  absWorkingDir: fileURLToPath(new URL("../", import.meta.url)),
  stdin: {
    contents: 'import { fullFormats as formats } from "ajv-formats/dist/formats.js";\n' + standaloneCode(ajv, validate),
    resolveDir: fileURLToPath(new URL("../", import.meta.url)),
  },
  bundle: true, platform: "browser", format: "esm",
  outfile: fileURLToPath(new URL(`${file}.validator.js`, contracts)),
  banner: {js: "// Generated by apps/web/scripts/generate-task-validator.mjs. Do not edit."},
});
writeFileSync(new URL(`${file}.validator.d.ts`, contracts),
  '// Generated. Do not edit.\nimport type { components } from "./api";\n' +
  `export default function validate(value: unknown): value is components["schemas"]["${model}"];\n`);
}
